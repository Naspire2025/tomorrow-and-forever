#!/usr/bin/env python3
"""Generate the static pages of the book site from _src/index.html.

Edit _src/index.html (and _src/pages.json for page titles and descriptions), then run:

    python3 build.py

It writes one page per view and language so every page has a real address:
    index.html, preview/, author/, buy/, contact/          (Arabic)
    en/index.html, en/preview/, en/author/, ...            (English)
plus 404.html and sitemap.xml. Commit the generated files with the source.
(_src/ starts with an underscore so GitHub Pages does not publish it.)
"""
import json
import re
from html import escape
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent
SRC = (ROOT / "_src" / "index.html").read_text(encoding="utf-8")
PAGES = json.loads((ROOT / "_src" / "pages.json").read_text(encoding="utf-8"))
SITE = PAGES["site"]
VIEWS = PAGES["views"]
LANGS = ("ar", "en")
LOCALE = {"ar": "ar_AR", "en": "en_US"}
OG_IMAGE_ALT = {"ar": "غلاف كتاب غداً وأبداً للدكتور محمد أبوشيخه", "en": "Cover of Tomorrow & Forever by Dr. Mohammad Abushaikha"}
AUTHOR = {"ar": "د. محمد أبوشيخه", "en": "Dr. Mohammad Abushaikha"}


def path_for(view, lang):
    return ("en/" if lang == "en" else "") + ("" if view == "home" else view + "/")


def head(view, lang, base, noindex=False):
    meta = PAGES[lang][view]
    url = SITE + path_for(view, lang)
    title, desc = escape(meta["title"]), escape(meta["description"])
    other = "en" if lang == "ar" else "ar"
    lines = [
        f'<base href="{base}">',
        f"<title>{title}</title>",
        f'<meta name="description" content="{desc}">',
        f'<meta name="author" content="{escape(AUTHOR[lang])}">',
        '<meta name="theme-color" content="#0E2621">',
    ]
    if noindex:
        lines.append('<meta name="robots" content="noindex">')
    else:
        lines += [
            f'<link rel="canonical" href="{url}">',
            f'<link rel="alternate" hreflang="ar" href="{SITE + path_for(view, "ar")}">',
            f'<link rel="alternate" hreflang="en" href="{SITE + path_for(view, "en")}">',
            f'<link rel="alternate" hreflang="x-default" href="{SITE + path_for(view, "ar")}">',
        ]
    lines += [
        '<link rel="icon" type="image/png" href="favicon.png">',
        '<link rel="apple-touch-icon" href="apple-touch-icon.png">',
        '<meta property="og:type" content="book">',
        f'<meta property="og:site_name" content="{escape(PAGES[lang]["home"]["title"].split(" · ")[0])}">',
        f'<meta property="og:locale" content="{LOCALE[lang]}">',
        f'<meta property="og:locale:alternate" content="{LOCALE[other]}">',
        f'<meta property="og:title" content="{title}">',
        f'<meta property="og:description" content="{desc}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:image" content="{SITE}og-image.jpg">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{escape(OG_IMAGE_ALT[lang])}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{title}">',
        f'<meta name="twitter:description" content="{desc}">',
        f'<meta name="twitter:image" content="{SITE}og-image.jpg">',
    ]
    return "\n".join(lines)


def static_href(m, lang):
    # href="#x" data-go="view" -> the view's folder, keeping #x when it is a section on the home page
    target, attrs, view = m.group(1), m.group(2), m.group(3)
    anchor = "" if target in VIEWS else "#" + target
    return f'href="{path_for(view, lang) + anchor}"{attrs}'


def render(view, lang, base, noindex=False):
    html = SRC
    html = html.replace('<html lang="ar" dir="rtl">', f'<html lang="{lang}" dir="{"rtl" if lang == "ar" else "ltr"}">', 1)
    html = html.replace("<!--GENERATED-->", "<!-- Generated by build.py from _src/index.html. Edit the source, then run: python3 build.py -->", 1)
    html = html.replace("<!--HEAD-->", head(view, lang, base, noindex), 1)
    html = html.replace("/*META*/null", json.dumps({l: PAGES[l] for l in LANGS}, ensure_ascii=False), 1)
    # open on the right view without waiting for the script
    html = html.replace('<div data-view="home" class="active">', '<div data-view="home">', 1)
    html = html.replace(f'<div data-view="{view}">', f'<div data-view="{view}" class="active">', 1)
    html = re.sub(r'href="#([\w-]+)"((?:\s+[\w-]+="[^"]*")*?\s+data-go="(\w+)")', lambda m: static_href(m, lang), html)
    for marker in ("<!--HEAD-->", "/*META*/null", "<!--GENERATED-->"):
        assert marker not in html, marker
    return html


def write(rel, text):
    out = ROOT / rel
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print("wrote", rel)


def main():
    for lang in LANGS:
        for view in VIEWS:
            rel = path_for(view, lang)
            depth = rel.count("/")
            write(rel + "index.html", render(view, lang, "../" * depth or "./"))
    # GitHub Pages serves 404.html for unknown paths at any depth, so it needs an absolute base
    write("404.html", render("home", "ar", urlparse(SITE).path, noindex=True))

    entries = []
    for view in VIEWS:
        for lang in LANGS:
            alts = "".join(
                f'\n    <xhtml:link rel="alternate" hreflang="{l}" href="{SITE + path_for(view, l)}"/>' for l in LANGS
            )
            entries.append(f"  <url>\n    <loc>{SITE + path_for(view, lang)}</loc>{alts}\n  </url>")
    write(
        "sitemap.xml",
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        + "\n".join(entries)
        + "\n</urlset>\n",
    )


if __name__ == "__main__":
    main()
